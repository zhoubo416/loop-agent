export type ApiErrorCode =
  | 'PROJECT_NOT_FOUND'
  | 'PROJECT_ACCESS_DENIED'
  | 'PROJECT_PAUSED'
  | 'PROJECT_COMPLETED'
  | 'PROJECT_NOT_COMPLETABLE'
  | 'SESSION_NOT_FOUND'
  | 'OBSERVATION_NOT_FOUND'
  | 'EVENT_NOT_FOUND'
  | 'ACTION_NOT_FOUND'
  | 'ACTION_INVALID_STATE'
  | 'ACTION_ALREADY_COMPLETED'
  | 'EXECUTION_NOT_FOUND'
  | 'RECOMMENDATION_NOT_FOUND'
  | 'RECOMMENDATION_ALREADY_RESOLVED'
  | 'RUN_NOT_FOUND'
  | 'RUN_ALREADY_RUNNING'
  | 'RUN_CONFLICT'
  | 'SCHEDULE_NOT_FOUND'
  | 'SCHEDULE_INVALID'
  | 'STATE_NOT_FOUND'
  | 'STATE_CONFLICT'
  | 'INVALID_AGENT_OUTPUT'
  | 'IDEMPOTENCY_CONFLICT'
  | 'USER_NOT_FOUND'
  | 'UNAUTHORIZED'
  | 'INTEGRATION_NOT_CONFIGURED'
  | 'INTEGRATION_AUTH_FAILED'
  | 'INTEGRATION_UNAVAILABLE'
  | 'VALIDATION_ERROR'
  | 'INTERNAL_ERROR'

const statusByCode: Record<ApiErrorCode, number> = {
  PROJECT_NOT_FOUND: 404,
  PROJECT_ACCESS_DENIED: 403,
  PROJECT_PAUSED: 409,
  PROJECT_COMPLETED: 409,
  PROJECT_NOT_COMPLETABLE: 422,
  SESSION_NOT_FOUND: 404,
  OBSERVATION_NOT_FOUND: 404,
  EVENT_NOT_FOUND: 404,
  ACTION_NOT_FOUND: 404,
  ACTION_INVALID_STATE: 409,
  ACTION_ALREADY_COMPLETED: 409,
  EXECUTION_NOT_FOUND: 404,
  RECOMMENDATION_NOT_FOUND: 404,
  RECOMMENDATION_ALREADY_RESOLVED: 409,
  RUN_NOT_FOUND: 404,
  RUN_ALREADY_RUNNING: 409,
  RUN_CONFLICT: 409,
  SCHEDULE_NOT_FOUND: 404,
  SCHEDULE_INVALID: 422,
  STATE_NOT_FOUND: 404,
  STATE_CONFLICT: 409,
  INVALID_AGENT_OUTPUT: 422,
  IDEMPOTENCY_CONFLICT: 409,
  USER_NOT_FOUND: 404,
  UNAUTHORIZED: 401,
  INTEGRATION_NOT_CONFIGURED: 422,
  INTEGRATION_AUTH_FAILED: 401,
  INTEGRATION_UNAVAILABLE: 502,
  VALIDATION_ERROR: 400,
  INTERNAL_ERROR: 500,
}

export class ApiError extends Error {
  readonly code: ApiErrorCode
  readonly status: number
  readonly details?: unknown

  constructor(code: ApiErrorCode, message: string, details?: unknown) {
    super(message)
    this.name = 'ApiError'
    this.code = code
    this.status = statusByCode[code]
    this.details = details
  }
}
